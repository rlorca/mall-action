export function textWidth(text, scale = 1) {
  return Math.max(0, String(text).length * 4 - 1) * scale;
}
export function text(ctx, text, x, y, color = "cream", scale = 1) {
  ctx.fillStyle = PAL[color] || color;
  let xx = Math.round(x);
  for (const char of String(text).toUpperCase()) {
    const bits = FONT[char] || FONT["?"];
    for (let i = 0; i < 15; i++)
      if (bits[i])
        ctx.fillRect(
          xx + (i % 3) * scale,
          Math.round(y) + Math.floor(i / 3) * scale,
          scale,
          scale,
        );
    xx += 4 * scale;
  }
}
function sprite(w, h, colors, paint) {
  const pixels = new Uint8Array(w * h);
  const r = (x, y, ww, hh, c = 1) => {
    for (let j = Math.max(0, y); j < Math.min(h, y + hh); j++)
      for (let i = Math.max(0, x); i < Math.min(w, x + ww); i++)
        pixels[j * w + i] = c;
  };
  const dot = (x, y, c = 1) => r(x, y, 1, 1, c);
  paint(r, dot);
  return { w, h, colors, pixels: [...pixels] };
}
