export function drawSprite(
  ctx,
  name,
  x,
  y,
  { flip = false, scale = 1, palette = null } = {},
) {
  const s = SPRITES[name];
  if (!s) return;
  x = Math.round(x);
  y = Math.round(y);
  const colors = palette || s.colors;
  for (let i = 0; i < s.pixels.length; i++) {
    const c = s.pixels[i];
    if (!c) continue;
    ctx.fillStyle = PAL[colors[c - 1]];
    const px = flip ? s.w - 1 - (i % s.w) : i % s.w;
    const py = Math.floor(i / s.w);
    const left = Math.round(x + px * scale),
      top = Math.round(y + py * scale);
    ctx.fillRect(
      left,
      top,
      Math.round(x + (px + 1) * scale) - left,
      Math.round(y + (py + 1) * scale) - top,
    );
  }
}
