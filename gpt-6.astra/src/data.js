export function template(id) {
  const s = STORES.find((s) => s.id === id);
  return {
    width: 256,
    height: 176,
    door: { x: 112, y: 160, w: 32, h: 16 },
    fixtures: (layouts[id] || []).map(([x, y], i) => ({
      id: i,
      x: x * 16,
      y: y * 16,
      w: 24,
      h: 16,
      kind:
        s.theme === "fashion" && i < 2
          ? "fitting"
          : s.theme === "toys"
            ? "toy"
            : s.theme,
      opened: false,
    })),
    decor:
      s.id === "sam" ? [{ x: 176, y: 128, w: 32, h: 16, kind: "booth" }] : [],
  };
}
