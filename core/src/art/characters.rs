//! Mall side-view characters (art agent 1). 16x24 canvas, facing RIGHT, feet on the bottom row.
//! Every sprite: at most 3 colours. Agent = [black, red, tan]; spy = [black, pale, white].
use super::Registry;
use crate::pixel::{pal, Sprite};

/// Build a sprite from rows, tolerant of sloppy hand-drawn art: rows are right-padded with transparent
/// pixels to `w`, and frames shorter than `h` are bottom-aligned (blank rows added on top).
pub(crate) fn mk(frames: &[Vec<String>], w: usize, h: usize, colors: [u8; 3]) -> Sprite {
    let fixed: Vec<Vec<String>> = frames
        .iter()
        .map(|f| {
            let mut rows: Vec<String> = f
                .iter()
                .map(|r| {
                    let mut r: String = r.chars().take(w).collect();
                    while r.chars().count() < w {
                        r.push('.');
                    }
                    r
                })
                .collect();
            assert!(rows.len() <= h, "frame too tall: {} > {h}", rows.len());
            while rows.len() < h {
                rows.insert(0, ".".repeat(w));
            }
            rows
        })
        .collect();
    let refs: Vec<Vec<&str>> = fixed.iter().map(|f| f.iter().map(String::as_str).collect()).collect();
    let slices: Vec<&[&str]> = refs.iter().map(|v| v.as_slice()).collect();
    Sprite::from_frames(&slices, colors)
}

/// Parse a multi-line block of art (blank lines at the edges ignored) into rows.
pub(crate) fn blk(s: &str) -> Vec<String> {
    s.lines().map(|l| l.trim()).filter(|l| !l.is_empty()).map(String::from).collect()
}

const AGENT: [u8; 3] = [pal::BLACK, pal::RED, pal::TAN];
const SPY: [u8; 3] = [pal::BLACK, pal::LGRAY, pal::WHITE];


/// One frame per block, all `w` x `h` (tolerant of short rows / short frames, see `mk`).
pub(crate) fn frames_of(blocks: &[&str], w: usize, h: usize, colors: [u8; 3]) -> Sprite {
    let f: Vec<Vec<String>> = blocks.iter().map(|b| blk(b)).collect();
    mk(&f, w, h, colors)
}

