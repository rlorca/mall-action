/// Build a 16x16 sprite from frames of ASCII rows; rows are padded/truncated to 16 columns, missing rows are blank.
fn spr(frames: &[&[&str]], cols: [u8; 3]) -> Sprite {
    let fr: Vec<Vec<String>> = frames
        .iter()
        .map(|f| {
            let mut rows: Vec<String> = f
                .iter()
                .map(|r| {
                    let mut s: String = r.chars().take(16).collect();
                    while s.chars().count() < 16 {
                        s.push('.');
                    }
                    s
                })
                .collect();
            while rows.len() < 16 {
                rows.push(".".repeat(16));
            }
            rows.truncate(16);
            rows
        })
        .collect();
    let refs: Vec<Vec<&str>> = fr.iter().map(|f| f.iter().map(|s| s.as_str()).collect()).collect();
    let r2: Vec<&[&str]> = refs.iter().map(|v| v.as_slice()).collect();
    Sprite::from_frames(&r2, cols)
}

fn swap23(rows: &[&str]) -> Vec<String> {
    rows.iter().map(|r| r.chars().map(|c| match c { '2' => '3', '3' => '2', c => c }).collect()).collect()
}

