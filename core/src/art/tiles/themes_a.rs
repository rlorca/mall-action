fn checker(a: u8, b: u8, sz: i32) -> Cv {
    let mut c = Cv::new(16, 16, a);
    for y in 0..16 {
        for x in 0..16 {
            if ((x / sz) + (y / sz)) % 2 == 1 {
                c.put(x, y, b);
            }
        }
    }
    c
}

