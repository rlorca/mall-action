// ---------------------------------------------------------------------------
// Drawing
// ---------------------------------------------------------------------------

export function textWidth(font: PixelFont, text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return (text.length * font.advance - (font.advance - font.w)) * scale;
}

/** Draw text with its top-left at (x, y). Unknown characters render as blanks. */
export function drawText(
  fb: Framebuffer,
  font: PixelFont,
  text: string,
  x: number,
  y: number,
  color: number,
  scale = 1,
): void {
  let cx = x | 0;
  for (const raw of text) {
    const ch = raw.toUpperCase();
    const bits = font.glyphs.get(ch);
    if (bits) {
      for (let gy = 0; gy < font.h; gy++) {
        for (let gx = 0; gx < font.w; gx++) {
          if (!bits[gy * font.w + gx]) continue;
          if (scale === 1) {
            fb.px(cx + gx, y + gy, color);
          } else {
            fb.rect(cx + gx * scale, y + gy * scale, scale, scale, color);
          }
        }
      }
    }
    cx += font.advance * scale;
  }
}

/** Centre text horizontally in a span. */
export function drawTextCentered(
  fb: Framebuffer,
  font: PixelFont,
  text: string,
  cx: number,
  y: number,
  color: number,
  scale = 1,
): void {
  drawText(fb, font, text, Math.round(cx - textWidth(font, text, scale) / 2), y, color, scale);
}

/** Text with a 1px outline, so it stays readable over busy backgrounds. */
export function drawTextOutlined(
  fb: Framebuffer,
  font: PixelFont,
  text: string,
  x: number,
  y: number,
  color: number,
  outline: number,
  scale = 1,
): void {
  for (const [ox, oy] of [
    [-1, 0],
    [1, 0],
    [0, -1],
    [0, 1],
  ]) {
    drawText(fb, font, text, x + ox, y + oy, outline, scale);
  }
  drawText(fb, font, text, x, y, color, scale);
}

export function drawTextCenteredOutlined(
  fb: Framebuffer,
  font: PixelFont,
  text: string,
  cx: number,
  y: number,
  color: number,
  outline: number,
  scale = 1,
): void {
  drawTextOutlined(
    fb,
    font,
    text,
    Math.round(cx - textWidth(font, text, scale) / 2),
    y,
    color,
    outline,
    scale,
  );
}
