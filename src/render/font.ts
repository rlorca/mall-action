import type { Framebuffer } from './pixels';

/**
 * Two pixel fonts, both defined as ASCII art in this file. Nothing is loaded.
 *
 *   FONT   5x7, advance 6 - the main face (HUD, banners, dialogue)
 *   TINY   3x5, advance 4 - store signs and other cramped labels
 *
 * Edit a glyph by editing its art. Every row must be exactly the declared
 * width or buildFont() throws at load time.
 */

export interface PixelFont {
  w: number;
  h: number;
  advance: number;
  glyphs: Map<string, Uint8Array>;
}

function buildFont(w: number, h: number, advance: number, art: Record<string, string>): PixelFont {
  const glyphs = new Map<string, Uint8Array>();
  for (const [ch, spec] of Object.entries(art)) {
    const rows = spec.split('/');
    if (rows.length !== h) throw new Error(`glyph '${ch}' has ${rows.length} rows, expected ${h}`);
    const bits = new Uint8Array(w * h);
    rows.forEach((row, y) => {
      if (row.length !== w) throw new Error(`glyph '${ch}' row ${y} is ${row.length}, expected ${w}`);
      for (let x = 0; x < w; x++) bits[y * w + x] = row[x] === '#' ? 1 : 0;
    });
    glyphs.set(ch, bits);
  }
  return { w, h, advance, glyphs };
}

