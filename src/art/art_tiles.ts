function floor(kind: FloorKind, colors: number[], seed: number): SpriteDef {
  return spriteFromFn(16, 16, colors, (x, y) => {
    switch (kind) {
      case 'checker':
        return ((x >> 3) + (y >> 3)) % 2 === 0 ? 1 : 2;
      case 'tile':
        if (x === 15 || y === 15) return 2;
        if ((x === 0 || y === 0) && x < 15 && y < 15) return 3;
        return 1;
      case 'planks': {
        const row = y >> 2;
        const off = (row % 2) * 8;
        if (y % 4 === 3) return 2;
        if ((x + off) % 16 === 0) return 2;
        return hash(x, y, seed) > 0.9 ? 3 : 1;
      }
      case 'carpet':
        if ((x + 2 * y) % 8 === 0 && y % 4 === 0) return 2;
        if (hash(x, y, seed) > 0.93) return 3;
        return 1;
      case 'grid':
        if (x % 8 === 0 || y % 8 === 0) return 2;
        if (x % 8 === 4 && y % 8 === 4) return 3;
        return 1;
      case 'diamond': {
        const dx = Math.abs((x % 16) - 7.5);
        const dy = Math.abs((y % 16) - 7.5);
        if (Math.abs(dx + dy - 7) < 0.6) return 3;
        return dx + dy < 7 ? 2 : 1;
      }
      case 'speckle': {
        const h = hash(x, y, seed);
        if (h > 0.96) return 3;
        if (h > 0.85) return 2;
        return 1;
      }
    }
  });
}

function wall(kind: WallKind, colors: number[]): SpriteDef {
  // 1 = base, 2 = dark, 3 = light
  return spriteFromFn(16, 16, colors, (x, y) => {
    if (y === 0) return 3;
    if (y >= 14) return 2; // baseboard
    switch (kind) {
      case 'panel':
        if (y === 1 || y === 13) return 2;
        if (x === 0 || x === 8) return 3;
        if (x === 7 || x === 15) return 2;
        return 1;
      case 'brick': {
        const row = (y - 1) >> 2;
        if ((y - 1) % 4 === 3) return 2;
        if ((x + (row % 2) * 4) % 8 === 0) return 2;
        return 1;
      }
      case 'stripe':
        return (x >> 2) % 2 === 0 ? 1 : 3;
      case 'neon':
        if (y === 5 || y === 10) return 3;
        return 1;
      case 'slat':
        return y % 3 === 0 ? 2 : 1;
    }
  });
}

