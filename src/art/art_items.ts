// fountain: stone basin with animated jets (1 = stone, 2 = water, 3 = spray)
const fountain = (f: number): SpriteDef =>
  spriteFromFn(32, 24, [C.LGREY, C.LBLUE, C.WHITE], (x, y) => {
    // basin
    if (y >= 17) {
      if (y === 17) return x >= 1 && x <= 30 ? 1 : 0;
      if (y === 18) return x >= 1 && x <= 30 ? (x >= 3 && x <= 28 ? 2 : 1) : 0;
      if (x < 2 || x > 29) return 0;
      if (y === 23 || x < 4 || x > 27) return 1;
      if (y <= 20) return (x + f * 3 + y * 5) % 9 === 0 ? 3 : 2; // water surface
      return (x + y) % 8 === 0 ? 3 : 1;
    }
    // central column and bowl
    if (y >= 10 && y <= 16 && x >= 14 && x <= 17) return 1;
    if (y === 10 && x >= 10 && x <= 21) return 1;
    if (y === 9 && x >= 11 && x <= 20) return 2;
    // jets: arcs from the bowl, animated
    const t = f * 2;
    for (const side of [-1, 1]) {
      for (let s = 0; s <= 12; s++) {
        const px = 15.5 + side * (s * 1.1);
        const py = 8 - s * 1.3 + s * s * 0.14 + (s > 8 ? (s - 8) * 0.6 : 0);
        if (Math.abs(x - px) < 0.8 && Math.abs(y - py) < 0.8) return (s + t) % 4 === 0 ? 3 : 2;
      }
    }
    // top plume
    if (x >= 15 && x <= 16 && y >= 2 && y <= 8) return (y + t) % 3 === 0 ? 3 : 2;
    if (y === 1 + (f % 2) && x >= 14 && x <= 17) return 3;
    // droplets
    if (y >= 11 && y <= 16 && hash(x, y, f) > 0.93 && (x < 12 || x > 19)) return 3;
    return 0;
  });
out.fountain_0 = fountain(0);
out.fountain_1 = fountain(1);
out.fountain_2 = fountain(2);

