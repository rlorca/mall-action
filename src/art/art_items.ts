// station wagon, side view facing right; wheels are separate sprites drawn at x~9 and x~45
out.wagon_body = spriteFromFn(64, 24, [C.CREAM, C.BROWN, C.BLACK], (x, y) => {
  const wells = [13.5, 49.5];
  for (const wx of wells) {
    const d = Math.hypot(x - wx, y - 19.5);
    if (d < 6.2 && y >= 13) return d < 5.2 ? 0 : 3;
  }
  if (y === 0) return x >= 8 && x <= 40 && x % 4 === 0 ? 3 : 0; // roof rack posts
  if (y === 1) return x >= 6 && x <= 42 ? 3 : 0; // rack rail
  // cabin with sloped windshield
  if (y >= 2 && y <= 8) {
    const right = 44 + (y - 2) * 1.5;
    if (x < 3 || x > right) return 0;
    if (x > right - 1) return 3;
    if (y === 2) return 1;
    const winRight = right - 2.5;
    if (y >= 3 && y <= 7) {
      if ((x >= 5 && x <= 16) || (x >= 19 && x <= 30) || (x >= 33 && x <= winRight)) return 3;
    }
    return 1;
  }
  if (y >= 9 && y <= 19) {
    if (x < 1 || x > 62) return 0;
    if (y === 9 && x > 58) return 0;
    if ((x <= 1 || x >= 62) && y >= 15) return 3; // bumpers
    if (x >= 61 && y >= 11 && y <= 12) return 1; // headlight
    if (y === 18 || y === 19) return y === 19 ? 3 : 1;
    // wood panel with cream trim
    if (y >= 11 && y <= 16 && x >= 3 && x <= 58) {
      if (y === 11 || y === 16 || x === 3 || x === 58) return 1;
      if (x === 18 || x === 31 || x === 44) return 1; // door seams
      return (x * 7 + y * 3) % 11 === 0 ? 3 : 2; // wood grain
    }
    if (y === 10 && (x === 18 || x === 31 || x === 44)) return 3;
    if (y === 10 && (x === 26 || x === 39)) return 3; // handles
    return 1;
  }
  return 0;
});
