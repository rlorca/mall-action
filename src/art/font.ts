export interface FontDef {
  name: string;
  w: number;
  h: number;
  advance: number;
  glyphs: Map<string, string[]>;
}

function build(name: string, table: Record<string, string>, w: number, h: number, advance: number): FontDef {
  const glyphs = new Map<string, string[]>();
  for (const [k, v] of Object.entries(table)) glyphs.set(k, v.split('/'));
  return { name, w, h, advance, glyphs };
}

export const FONT5 = build('ui', F5, 5, 7, 6);
export const FONT3 = build('sign', F3, 3, 5, 4);

export function hasGlyph(font: FontDef, ch: string): boolean {
  return font.glyphs.has(ch.toUpperCase());
}

export function textWidth(font: FontDef, text: string, scale = 1): number {
  if (!text.length) return 0;
  return (text.length * font.advance - (font.advance - font.w)) * scale;
}
