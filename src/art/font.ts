function expand8(src: string): string[] {
  const rows = src.split('|').map((r) => '.' + r + '..');
  rows.push('........');
  return rows;
}
function expand3(src: string): string[] {
  return src.split('|');
}

const cache8 = new Map<string, string[] | null>();
const cache3 = new Map<string, string[] | null>();

function key(ch: string): string {
  return ch.toUpperCase();
}

export function hasGlyph8(ch: string): boolean {
  return key(ch) in G5;
}
export function hasGlyph3(ch: string): boolean {
  return key(ch) in G3;
}

/** 8 rows of 8 chars ('.'/'#'), or null when the character has no glyph. */
export function glyph8(ch: string): string[] | null {
  const k = key(ch);
  if (cache8.has(k)) return cache8.get(k)!;
  const g = k in G5 ? expand8(G5[k]) : null;
  cache8.set(k, g);
  return g;
}
/** 5 rows of 3 chars ('.'/'#'), or null when the character has no glyph. */
export function glyph3(ch: string): string[] | null {
  const k = key(ch);
  if (cache3.has(k)) return cache3.get(k)!;
  const g = k in G3 ? expand3(G3[k]) : null;
  cache3.set(k, g);
  return g;
}
