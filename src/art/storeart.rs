    use crate::engine::sprite::Sprite;
    use std::sync::OnceLock;

    const KEYS: [&str; 8] = ["floor", "wall", "counter", "decor", "shelf", "shelf.open", "rack", "rack.open"];

    // Local lookup so this test file only depends on this module's own defs.
    fn all() -> &'static Vec<Sprite> {
        static ALL: OnceLock<Vec<Sprite>> = OnceLock::new();
        ALL.get_or_init(|| defs().iter().map(build_def).collect())
    }
    fn get_sprite(name: &str) -> &'static Sprite {
        all().iter().find(|s| s.name == name).unwrap_or_else(|| panic!("unknown sprite: {}", name))
    }
    fn tile(theme: &str, key: &str) -> &'static Sprite {
        get_sprite(&format!("st.{}.{}", theme, key))
    }
    fn frame_of(s: &Sprite, f: usize) -> &[u8] {
        &s.frames[f]
    }
    fn diff(a: &Sprite, b: &Sprite, fa: usize, fb: usize) -> i32 {
        let x = frame_of(a, fa);
        let y = frame_of(b, fb);
        (0..x.len()).filter(|&i| x[i] != y[i]).count() as i32
    }
    fn diff0(a: &Sprite, b: &Sprite) -> i32 {
        diff(a, b, 0, 0)
    }
    fn opaque(s: &Sprite) -> bool {
        frame_of(s, 0).iter().all(|&v| v != TRANSPARENT)
    }
    fn distinct_colors(s: &Sprite) -> usize {
        let mut v: Vec<u8> = frame_of(s, 0).to_vec();
        v.sort();
        v.dedup();
        v.len()
    }

    #[test]
    fn defines_94_sprites_with_unique_names() {
        let mut names: Vec<&str> = all().iter().map(|s| s.name.as_str()).collect();
        assert_eq!(names.len(), 9 * 8 + 14 + 8);
        names.sort();
        names.dedup();
        assert_eq!(names.len(), 94);
    }

    #[test]
    fn store_theme_tiles() {
        for theme in ThemeId::ALL {
            let theme = theme.as_str();
            // has 8 tiles of 16x16 that are fully opaque
            for k in KEYS {
                let s = tile(theme, k);
                assert_eq!((s.w, s.h), (16, 16), "{}", k);
                assert!(opaque(s), "{}.{} has transparent pixels", theme, k);
            }
            // has 8 pairwise different tiles
            for i in 0..KEYS.len() {
                for j in (i + 1)..KEYS.len() {
                    assert!(diff0(tile(theme, KEYS[i]), tile(theme, KEYS[j])) > 20, "{}: {} vs {}", theme, KEYS[i], KEYS[j]);
                }
            }
            // shows opened shelves and racks clearly different from the closed ones
            assert!(diff0(tile(theme, "shelf"), tile(theme, "shelf.open")) >= 40, "shelf");
            assert!(diff0(tile(theme, "rack"), tile(theme, "rack.open")) >= 40, "rack");
            // has a textured floor (at least 2 colours) and a wall with a lit top edge differing from the face
            assert!(distinct_colors(tile(theme, "floor")) >= 2);
            let wall = tile(theme, "wall");
            let majority = |y0: usize, y1: usize| -> u8 {
                let mut count: Vec<(u8, i32)> = Vec::new();
                for y in y0..y1 {
                    for x in 0..16 {
                        let v = wall.frames[0][y * 16 + x];
                        match count.iter_mut().find(|e| e.0 == v) {
                            Some(e) => e.1 += 1,
                            None => count.push((v, 1)),
                        }
                    }
                }
                // stable descending sort by count (first-seen wins ties, like Array.sort on Map entries)
                count.sort_by(|a, b| b.1.cmp(&a.1));
                count[0].0
            };
            assert_ne!(majority(0, 3), majority(5, 15), "{} wall top vs face", theme);
            // floor tiles seamlessly
            let f = tile(theme, "floor");
            let at = |x: usize, y: usize| f.frames[0][(y & 15) * 16 + (x & 15)];
            let mut same_right = 0i32;
            let mut same_inner = 0i32;
            for y in 0..16 {
                if at(15, y) == at(16, y) {
                    same_right += 1;
                }
                if at(7, y) == at(8, y) {
                    same_inner += 1;
                }
            }
            assert!((same_right - same_inner).abs() <= 10);
        }
    }

