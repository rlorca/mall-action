/** Required sizes (checked by tests): mall characters 16x24, store characters 16x16. */
export const SPRITE_SIZES: Record<string, [number, number]> = {};
for (const k of Object.keys(SPRITES)) {
  if (/^(ag_|sp_|wk_|wk2_|jn_|cop)/.test(k)) SPRITE_SIZES[k] = [16, 24];
  else if (/^(sag_|ssp_|bot|clerk|toy|pkg|puff)/.test(k)) SPRITE_SIZES[k] = [16, 16];
  else if (/^pu_/.test(k)) SPRITE_SIZES[k] = [12, 12];
}

export function S(name: string): Sprite {
  const s = SPRITES[name];
  if (!s) throw new Error('missing sprite: ' + name);
  return s;
}
