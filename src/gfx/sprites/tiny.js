// 3×5 micro font for text baked into signage art (FOR LEASE, 70% OFF…). Returns rows using `ch` as ink.
const G = {
  A: ['.#.', '#.#', '###', '#.#', '#.#'], C: ['###', '#..', '#..', '#..', '###'], E: ['###', '#..', '##.', '#..', '###'],
  F: ['###', '#..', '##.', '#..', '#..'], G: ['###', '#..', '#.#', '#.#', '###'], H: ['#.#', '#.#', '###', '#.#', '#.#'],
  I: ['###', '.#.', '.#.', '.#.', '###'], L: ['#..', '#..', '#..', '#..', '###'], M: ['#.#', '###', '###', '#.#', '#.#'],
  N: ['##.', '#.#', '#.#', '#.#', '#.#'], O: ['###', '#.#', '#.#', '#.#', '###'], R: ['##.', '#.#', '##.', '#.#', '#.#'],
  S: ['###', '#..', '###', '..#', '###'], T: ['###', '.#.', '.#.', '.#.', '.#.'], V: ['#.#', '#.#', '#.#', '#.#', '.#.'],
  0: ['###', '#.#', '#.#', '#.#', '###'], 7: ['###', '..#', '.#.', '.#.', '.#.'], '%': ['#.#', '..#', '.#.', '#..', '#.#'],
  '!': ['.#.', '.#.', '.#.', '...', '.#.'], ' ': ['...', '...', '...', '...', '...'],
};

export function tinyText(str, ch = '1') {
  const rows = ['', '', '', '', ''];
  [...str].forEach((c, i) => {
    const g = G[c] ?? G[' '];
    for (let y = 0; y < 5; y++) rows[y] += (i ? '.' : '') + g[y].replace(/#/g, ch);
  });
  return rows;
}
