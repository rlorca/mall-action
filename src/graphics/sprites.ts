import { PAL } from "./palette";

export type SpriteData = {
  width: number;
  height: number;
  colors: string[]; // Up to 3 colors (index 1, 2, 3). Index 0 is transparent.
  pixels: number[]; // Width * Height array of palette indices 0..3
};

/**
 * Helper to construct a SpriteData ensuring <= 3 non-transparent colors.
 */
export function createSprite(
  width: number,
  height: number,
  colors: [string, string, string] | [string, string] | [string],
  pattern: string
): SpriteData {
  const cleanPattern = pattern.replace(/\s+/g, "");
  if (cleanPattern.length !== width * height) {
    throw new Error(`Pattern size mismatch: expected ${width * height} chars, got ${cleanPattern.length}`);
  }

  const paletteColors = [PAL.TRANSPARENT, ...colors];
  const pixels: number[] = [];

  for (let i = 0; i < cleanPattern.length; i++) {
    const char = cleanPattern[i];
    const val = char === "." ? 0 : parseInt(char, 10);
    pixels.push(val);
  }

  return {
    width,
    height,
    colors: paletteColors,
    pixels,
  };
}

