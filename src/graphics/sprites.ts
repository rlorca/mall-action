/**
 * Draws a sprite data directly to a Canvas2D context.
 */
export function drawSprite(
  ctx: CanvasRenderingContext2D,
  sprite: SpriteData,
  x: number,
  y: number,
  flipX: boolean = false
) {
  const roundX = Math.round(x);
  const roundY = Math.round(y);

  for (let py = 0; py < sprite.height; py++) {
    for (let px = 0; px < sprite.width; px++) {
      const pIdx = sprite.pixels[py * sprite.width + px];
      if (pIdx === 0) continue;

      const drawPx = flipX ? sprite.width - 1 - px : px;
      ctx.fillStyle = sprite.colors[pIdx];
      ctx.fillRect(roundX + drawPx, roundY + py, 1, 1);
    }
  }
}

