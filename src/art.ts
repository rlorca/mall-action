export interface Sprite {
  w: number;
  h: number;
  pixels: string[];
  colors: string[];
}
const registry: Record<string, Sprite> = {};
function add(name: string, rows: string[], cols: number[], w = 16, h = 16) {
  const pixels = Array.from({ length: h }, (_, y) =>
    (rows[y] ?? "").padEnd(w, ".").slice(0, w),
  );
  registry[name] = { w, h, pixels, colors: cols.map((i) => palette[i]) };
}
