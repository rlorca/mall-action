function tall(rows: string[]) {
  return [
    ...rows.slice(0, 6),
    ...rows.slice(6, 12).flatMap((r) => [r, r]),
    ...rows.slice(12, 16).flatMap((r, i) => (i < 2 ? [r, r] : [r])),
  ];
}
