export function glyph(c: string) {
  return glyphData[c.toUpperCase()] ?? glyphData["?"];
}
export function validateArt() {
  return Object.entries(sprites).every(
    ([, s]) =>
      s.pixels.length === s.h &&
      s.pixels.every(
        (r) =>
          r.length === s.w &&
          [...r].every((c) => c === "." || (+c >= 1 && +c <= s.colors.length)),
      ) &&
      s.colors.length <= 3,
  );
}
