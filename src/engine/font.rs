//! Two bitmap fonts, both uppercase-only (lowercase is drawn as uppercase):
//!  - MAIN: 5x7 glyphs, 6 px advance, 8 px line height. HUD, banners, bubbles.
//!  - TINY: 3x5 glyphs, 4 px advance, 6 px line height. Storefront signs (an 18-char
//!    store name = 71 px, which fits an ~80 px sign).

use super::framebuffer::Framebuffer;

pub struct Font {
    pub name: &'static str,
    pub glyph_w: i32,
    pub glyph_h: i32,
    pub advance: i32,
    pub line_height: i32,
    /// Glyph rows (one byte per row, MSB-left within `glyph_w` bits), in table order.
    pub glyphs: &'static [(char, &'static [u8])],
}

impl Font {
    pub fn glyph(&self, ch: char) -> Option<&'static [u8]> {
        // Map semantics: the last entry for a char wins (tables have no duplicates).
        self.glyphs.iter().rev().find(|(c, _)| *c == ch).map(|(_, g)| *g)
    }
    pub fn has(&self, ch: char) -> bool {
        self.glyph(ch).is_some()
    }
}

